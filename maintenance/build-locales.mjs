import { readFile, writeFile, mkdir } from 'node:fs/promises'
const source = new URL('../i18n/locales/', import.meta.url)
const destination = new URL('../public/filejet-offline/locales/', import.meta.url)
const writeChanged = async (file, content) => {
    const previous = await readFile(file, 'utf8').catch(error => { if (error.code !== 'ENOENT') throw error; return null })
    if (previous !== content) await writeFile(file, content)
}
await mkdir(destination, { recursive: true })
const catalogs = {}
for (const language of ['en', 'tr', 'de']) {
    const content = await readFile(new URL(`${language}.json`, source), 'utf8')
    catalogs[language] = JSON.parse(content)
    await writeChanged(new URL(`${language}.json`, destination), content)
}
const generated = new URL('../shared/generated/', import.meta.url)
await mkdir(generated, { recursive: true })
await writeChanged(new URL('messageCatalog.ts', generated), '// Generated by npm run locales:build. Edit i18n/locales instead.\nexport const messageCatalog: Record<string, Record<string, string>> = ' + JSON.stringify(catalogs, null, 2) + '\n')
